    /// <summary>
    /// Everything that decides how a player character looks: the look fields of the unit packets (0x9fd/0x9fe/0x9ff),
    /// ZC_SPRITE_CHANGE (0x01d7) and the char-select CHARACTER_INFO. See research/appearance_layers.md §1-§2.
    /// </summary>
    public sealed class PlayerLook
    {
        // rAthena src/map/map.hpp enum _look (lines 595-612)
        public const int LookBase = 0, LookHair = 1, LookWeapon = 2, LookHeadBottom = 3, LookHeadTop = 4, LookHeadMid = 5,
            LookHairColor = 6, LookClothesColor = 7, LookShield = 8, LookShoes = 9, LookBody = 10, LookResetCostumes = 11,
            LookRobe = 12, LookBody2 = 13;

        public int Job, Sex, Hair, HairColor, ClothesColor;
        /// <summary>Right hand. Item id on the wire (unit packets, ZC_SPRITE_CHANGE: rAthena pc.cpp update_look), or a weapon
        /// view/type id below <see cref="AppearanceDb.WeaponViewMax"/> (char select sends status.weapon = W_* type).</summary>
        public int Weapon;
        /// <summary>Left hand. Item id on the wire, or a shield view id below <see cref="AppearanceDb.WeaponViewMax"/>
        /// (char select sends status.shield = item_db View, rAthena pc.cpp:12181-12196).</summary>
        public int Shield;
        public int HeadBottom, HeadTop, HeadMid, Robe;
        /// <summary>LOOK_BODY2: 0 normal outfit, 1 costume_1 outfit (rAthena clif.cpp:3936-3947 sends only 0/1 for this PACKETVER).</summary>
        public int Body2;

        public PlayerLook Clone() => (PlayerLook)MemberwiseClone();

        public bool SameAs(PlayerLook o) =>
            o != null && Job == o.Job && Sex == o.Sex && Hair == o.Hair && HairColor == o.HairColor && ClothesColor == o.ClothesColor &&
            Weapon == o.Weapon && Shield == o.Shield && HeadBottom == o.HeadBottom && HeadTop == o.HeadTop && HeadMid == o.HeadMid &&
            Robe == o.Robe && Body2 == o.Body2;

        /// <summary>Char-select CHARACTER_INFO (rAthena char.cpp:1805-1852): accessory = head_bottom, accessory2 = head_top,
        /// accessory3 = head_mid, headpalette = hair colour, bodypalette = clothes colour, robePalette = robe view, body = 0/1.</summary>
        public static PlayerLook FromCharInfo(Loki.Net.CharInfo c) => new PlayerLook
        {
            Job = c.Job, Sex = c.Sex, Hair = c.Head, HairColor = c.HeadPalette, ClothesColor = c.BodyPalette,
            Weapon = c.Weapon, Shield = c.Shield, HeadBottom = c.Accessory, HeadTop = c.Accessory2, HeadMid = c.Accessory3,
            Robe = c.RobePalette, Body2 = c.Body,
        };

        /// <summary>Applies one ZC_SPRITE_CHANGE (type, val, val2). True when a field changed.</summary>
        public bool ApplyChange(int type, int val, int val2)
        {
            switch (type)
            {
                case LookBase: return Set(ref Job, val);
                case LookHair: return Set(ref Hair, val);
                case LookWeapon: { bool a = Set(ref Weapon, val); bool b = Set(ref Shield, val2); return a || b; } // clif.cpp:4095-4106
                case LookHeadBottom: return Set(ref HeadBottom, val);
                case LookHeadTop: return Set(ref HeadTop, val);
                case LookHeadMid: return Set(ref HeadMid, val);
                case LookHairColor: return Set(ref HairColor, val);
                case LookClothesColor: return Set(ref ClothesColor, val);
                case LookShield: return Set(ref Shield, val);   // never sent for non-NPCs in this build; kept for completeness
                case LookRobe: return Set(ref Robe, val);
                case LookBody2: return Set(ref Body2, val);
                default: return false; // shoes, body, reset-costumes: not drawn by the client (rb MapEngine/Entity.js:1369-1377)
            }
        }

        private static bool Set(ref int field, int v) { if (field == v) return false; field = v; return true; }
    }

    /// <summary>
    /// Look-up tables for player equipment sprites: StreamingAssets/data/appearance.txt (Latin-1 = CP949 bytes, like
    /// spritenames.txt) and itemviews.tsv. Both are generated by tools/appearance/build_appearance.py.
    /// </summary>
    public static class AppearanceDb
    {
        /// <summary>Layer ids of the client's GetLayerPriority(direction, layer, acc_id) (tb_layer_priority.lub disassembly):
        /// 2 → Default_Bottom, 3 → Default_Top, 4 → Default_Mid, 8 → Default_Robe.</summary>
        public const int LayerBottom = 2, LayerTop = 3, LayerMid = 4, LayerRobe = 8;
        /// <summary>Values below this are already weapon view/type ids, not item ids (roBrowserLegacy WeaponType.MAX = 103,
        /// DB/Items/WeaponType.js:115; getWeaponViewID DBManager.js:2180-2202). Item ids start far above it.</summary>
        public const int WeaponViewMax = 103;

        private struct LayerEntry { public bool HasDefault; public int Default; public int[] Dir; }
        private struct ItemView { public int Type, ClassNum, WeaponType; public bool LeftHand; }

        private static bool _loaded;
        private static readonly Dictionary<int, string> _wjob = new Dictionary<int, string>(), _wjob2 = new Dictionary<int, string>(),
            _pal = new Dictionary<int, string>(), _pal2 = new Dictionary<int, string>(), _shield = new Dictionary<int, string>(),
            _trail = new Dictionary<int, string>(), _costumeName = new Dictionary<int, string>();
        private static readonly Dictionary<int, int> _wexp = new Dictionary<int, int>(), _costume = new Dictionary<int, int>();
        private static readonly Dictionary<int, LayerEntry> _layers = new Dictionary<int, LayerEntry>();
        private static readonly Dictionary<int, ItemView> _items = new Dictionary<int, ItemView>();
        // WeaponAction: (job, sex or -1, weapon type) → 0/1/2 (ATTACK1/2/3)
        private static readonly Dictionary<(int, int, int), int> _attack = new Dictionary<(int, int, int), int>();
        private static readonly HashSet<int> _attackJobs = new HashSet<int>();
        // TB_Layer_Priority.Default_* as read from tb_layer_priority.lub; replaced by the file's layerdef rows.
        private static int _defMid = 100, _defTop = 200, _defBottom = 300, _defRobe = 400;

        public static int DefaultRobe { get { EnsureLoaded(); return _defRobe; } }

        public static void EnsureLoaded()
        {
            if (_loaded) return;
            LoadFiles(Loki.Data.ClientData.File("appearance.txt"), Loki.Data.ClientData.File("itemviews.tsv")); // w3data: the per-user copy first
        }

        /// <summary>Loads appearance.txt and itemviews.tsv from a folder (EnsureLoaded uses StreamingAssets/data).</summary>
        public static void LoadFrom(string dir) => LoadFiles(Path.Combine(dir, "appearance.txt"), Path.Combine(dir, "itemviews.tsv"));

        /// <summary>Loads the two tables from these files (client wave 3b, w3data: EnsureLoaded passes Data.ClientData's choice).</summary>
        public static void LoadFiles(string p, string q)
        {
            _loaded = true;
            if (File.Exists(p))
            {
                foreach (var line in File.ReadAllLines(p, RoReader.Latin1))
                {
                    if (line.Length == 0 || line[0] == '#') continue;
                    var f = line.Split('\t');
                    if (f.Length < 3) continue;
                    if (f[0] == "watk")
                    {
                        if (f.Length >= 5 && int.TryParse(f[1], out int aj) && int.TryParse(f[2], out int asx) && int.TryParse(f[3], out int awt) && int.TryParse(f[4], out int ai))
                        { _attack[(aj, asx, awt)] = ai; _attackJobs.Add(aj); }
                        continue;
                    }
                    if (f[0] == "layerdef")
                    {
                        if (!int.TryParse(f[2], out int dv)) continue;
                        switch (f[1]) { case "Mid": _defMid = dv; break; case "Top": _defTop = dv; break; case "Bottom": _defBottom = dv; break; case "Robe": _defRobe = dv; break; }
                        continue;
                    }
                    if (!int.TryParse(f[1], out int id)) continue;
                    switch (f[0])
                    {
                        case "wjob": _wjob[id] = f[2]; break;
                        case "wjob2": _wjob2[id] = f[2]; break;
                        case "pal": _pal[id] = f[2]; break;
                        case "pal2": _pal2[id] = f[2]; break;
                        case "shield": _shield[id] = f[2]; break;
                        case "trail": _trail[id] = f[2]; break;
                        case "costumename": _costumeName[id] = f[2]; break;
                        case "wexp": if (int.TryParse(f[2], out int b)) _wexp[id] = b; break;
                        case "costume": if (int.TryParse(f[2], out int c)) _costume[id] = c; break;
                        case "layer":
                        {
                            var e = new LayerEntry();
                            if (f[2] != "-" && int.TryParse(f[2], out int def)) { e.HasDefault = true; e.Default = def; }
                            if (f.Length > 3 && f[3].Length > 0)
                            {
                                e.Dir = new int[8];
                                for (int i = 0; i < 8; i++) e.Dir[i] = int.MinValue;
                                foreach (var kv in f[3].Split(','))
                                {
                                    int eq = kv.IndexOf('=');
                                    if (eq > 0 && int.TryParse(kv.Substring(0, eq), out int d) && int.TryParse(kv.Substring(eq + 1), out int v) && d >= 0 && d < 8) e.Dir[d] = v;
                                }
                            }
                            _layers[id] = e;
                            break;
                        }
                    }
                }
            }
            else Debug.LogError("[AppearanceDb] missing " + p);

            if (File.Exists(q))
            {
                foreach (var line in File.ReadAllLines(q))
                {
                    var f = line.Split('\t');
                    if (f.Length < 5 || !int.TryParse(f[0], out int id)) continue;
                    int.TryParse(f[1], out int type); int.TryParse(f[2], out int cn); int.TryParse(f[3], out int wt);
                    _items[id] = new ItemView { Type = type, ClassNum = cn, WeaponType = wt, LeftHand = f[4] == "1" };
                }
            }
            else Debug.LogError("[AppearanceDb] missing " + q);
            Debug.Log($"[AppearanceDb] {_wjob.Count} weapon folders, {_pal.Count} palettes, {_layers.Count} layer overrides, {_items.Count} item views");
        }

        public static string WeaponJob(int job) { EnsureLoaded(); return _wjob.TryGetValue(job, out var s) ? s : null; }
        public static string WeaponJob2(int job) { EnsureLoaded(); return _wjob2.TryGetValue(job, out var s) ? s : null; }
        public static string PalName(int job) { EnsureLoaded(); return _pal.TryGetValue(job, out var s) ? s : null; }
        public static string PalName2(int job) { EnsureLoaded(); return _pal2.TryGetValue(job, out var s) ? s : null; }
        public static string ShieldName(int view) { EnsureLoaded(); return _shield.TryGetValue(view, out var s) ? s : null; }
        public static string TrailName(int weaponType) { EnsureLoaded(); return _trail.TryGetValue(weaponType, out var s) && s.Length > 0 ? s : null; }
        /// <summary>*_2ND costume job id for LOOK_BODY2 = 1, or 0 when the job has no costume outfit.</summary>
        public static int CostumeJob(int job) { EnsureLoaded(); return _costume.TryGetValue(job, out int c) ? c : 0; }
        public static string CostumeBodyName(int costumeJob) { EnsureLoaded(); return _costumeName.TryGetValue(costumeJob, out var s) ? s : null; }

        /// <summary>Client GetRealWeaponId (weapontable_f.lub): Expansion_Weapon_IDs[view] or the view itself.</summary>
        public static int BaseWeaponType(int view) { EnsureLoaded(); return _wexp.TryGetValue(view, out int b) ? b : view; }

        /// <summary>
        /// Client GetLayerPriority(direction, layer, acc_id) from tb_layer_priority.lub: Items_List[acc_id].Direction[direction],
        /// then Items_List[acc_id].Default, then the layer default (StallLayerTable is nil in this client).
        /// direction is the drawn ACT direction (0 = facing the camera … 4 = back to the camera).
        /// </summary>
        public static int LayerPriority(int direction, int layer, int accId)
        {
            EnsureLoaded();
            if (accId > 0 && _layers.TryGetValue(accId, out var e))
            {
                if (e.Dir != null && direction >= 0 && direction < 8 && e.Dir[direction] != int.MinValue) return e.Dir[direction];
                if (e.HasDefault) return e.Default;
            }
            switch (layer)
            {
                case LayerBottom: return _defBottom;
                case LayerTop: return _defTop;
                case LayerMid: return _defMid;
                case LayerRobe: return _defRobe;
                default: return -1;
            }
        }

        /// <summary>
        /// PC attack action group for a job/sex/weapon type (roBrowserLegacy getWeaponAction DBManager.js + DB/Jobs/WeaponAction.js;
        /// EntityAction.js:94-112 maps 0/1/2 to ATTACK1/ATTACK2/ATTACK3 = groups 5/10/11, :166-172). A job or weapon type not in
        /// the table uses ATTACK1. The client's weapon ACTs only draw the weapon in the groups this table picks (e.g.
        /// 검사_남_검.act has visible layers in groups 4 and 10 only).
        /// </summary>
        public static int AttackActionGroup(int job, int sex, int weaponType)
        {
            EnsureLoaded();
            int idx = 0;
            if (_attackJobs.Contains(job) && !_attack.TryGetValue((job, sex, weaponType), out idx) && !_attack.TryGetValue((job, -1, weaponType), out idx)) idx = 0;
            return idx == 1 ? 10 : idx == 2 ? 11 : 5;
        }

        /// <summary>Weapon type the attack motion depends on (rb getWeaponType(weapon, true)): the dual-wield W_DOUBLE_* type
        /// when both hands hold combinable weapons, else the right-hand base type; 0 = bare hands.</summary>
        public static int AttackWeaponType(PlayerLook look)
        {
            int right = look.Weapon, left = look.Shield;
            if (right <= 0 && left > 0 && IsWeaponItem(left)) { right = left; left = 0; }
            int rView = WeaponView(right);
            if (rView <= 0) return 0;
            int rType = BaseWeaponType(rView);
            if (left > 0 && IsWeaponItem(left))
            {
                int combo = DualWieldView(rType, BaseWeaponType(WeaponView(left)));
                if (combo > 0) return combo;
            }
            return rType;
        }

        /// <summary>Weapon view id for a wire value: below 103 it already is one; otherwise the item's client ClassNum, else its
        /// rAthena weapon SubType (base type). 0 = nothing to draw.</summary>
        public static int WeaponView(int value)
        {
            if (value <= 0) return 0;
            if (value < WeaponViewMax) return value;
            EnsureLoaded();
            if (_items.TryGetValue(value, out var it))
            {
                if (it.ClassNum > 0) return it.ClassNum;
                if (it.WeaponType > 0) return it.WeaponType;
            }
            return 0;
        }

        /// <summary>Shield view id (ShieldTable index) for a wire value: below 103 it already is one, else the item's ClassNum.</summary>
        public static int ShieldView(int value)
        {
            if (value <= 0) return 0;
            if (value < WeaponViewMax) return value;
            EnsureLoaded();
            return _items.TryGetValue(value, out var it) && it.ClassNum > 0 ? it.ClassNum : 0;
        }

        /// <summary>True when a left-hand wire value is a weapon item (dual wield) rather than a shield. Uses the rAthena item
        /// Type; items unknown to rAthena fall back to roBrowserLegacy's shield id ranges (DBManager.js:1456-1463).</summary>
        public static bool IsWeaponItem(int value)
        {
            if (value < WeaponViewMax) return false;
            EnsureLoaded();
            if (_items.TryGetValue(value, out var it) && it.Type >= 0) return it.Type == 5;
            bool shieldRange = (value >= 2100 && value <= 2199) || (value >= 28900 && value <= 28999) || (value >= 460000 && value <= 460099);
            return !shieldRange;
        }

        /// <summary>Client wave 3 (w3equip): the item's rAthena weapon SubType as a W_* number (itemviews.tsv column 4), -1 when unknown.</summary>
        public static int WeaponSubType(int itemId) { EnsureLoaded(); return _items.TryGetValue(itemId, out var it) ? it.WeaponType : -1; }

        /// <summary>rAthena pc_calcweapontype (pc.cpp:1516-1556): right + left base type → W_DOUBLE_* view (25 DD, 26 SS,
        /// 27 AA, 28 DS, 29 DA, 30 SA), 0 when the pair has no dual-wield type.</summary>
        public static int DualWieldView(int right, int left)
        {
            const int D = 1, S = 2, A = 6;
            switch (right)
            {
                case D: return left == D ? 25 : left == S ? 28 : left == A ? 29 : 0;
                case S: return left == D ? 28 : left == S ? 26 : left == A ? 30 : 0;
                case A: return left == D ? 29 : left == S ? 30 : left == A ? 27 : 0;
                default: return 0;
            }
        }
    }

    /// <summary>
    /// Resolves a <see cref="PlayerLook"/> to sprite files and hands them to an <see cref="ActorSprite"/>. Every optional layer
    /// walks a list of candidate paths and takes the first that exists, so missing item sprites fall back to the base type
    /// and never throw; each path that resolves to nothing is logged once.
    /// </summary>
    public static class PlayerAppearance
    {
        // CP949 folder/file names as Latin-1 (byte-exact; checked against the GRF listing)
        private const string Shield = "\u00b9\u00e6\u00c6\u00d0";            // 방패
        private const string ShieldSuffix = "_\u00b9\u00e6\u00c6\u00d0";     // _방패
        private const string BodyPal = "\u00b8\u00f6";                        // 몸
        private const string HairPal = "\u00b8\u00d3\u00b8\u00ae";            // 머리
        private const string Slash = "_\u00b0\u00cb\u00b1\u00a4";             // _검광

        private static readonly HashSet<string> _warned = new HashSet<string>();
        private static readonly List<string> _tmp = new List<string>();

        private static void Missing(string what, string detail)
        {
            if (_warned.Add(what + "|" + detail)) Debug.Log($"[Look] no {what} sprite for {detail}");
        }

        /// <param name="mountJob">Client wave 2: the mounted class drawn instead of the job while riding (dragon, warg, mado gear, gryphon — the
        /// server keeps the base class for those; roBrowser DB/Jobs/MountTable.js): body, weapon, shield and garment use it, the body palette
        /// keeps the base job (EntityView.js:165-168, 608). 0 = not riding.</param>
        public static void Apply(ActorSprite s, PlayerLook look, RoAssets a, int mountJob = 0) =>
            Apply(s, look, a, new UnitLooks.Drawn { Job = mountJob > 0 ? mountJob : look.Job, Doram = RoNames.IsDoram(mountJob > 0 ? mountJob : look.Job) });

        /// <summary>Client wave 4 (w4units): the look drawn as <paramref name="drawn"/> says (Sprites/UnitLooks.cs): the class (mount,
        /// boarding mount, costume outfit), a body name that replaces the class's own (a coloured dragon), the race folder (a Doram keeps
        /// its folder in a costume outfit when the GRF has the Doram outfit), and the orc head (e_option ORCISH).</summary>
        public static void Apply(ActorSprite s, PlayerLook look, RoAssets a, UnitLooks.Drawn drawn)
        {
            AppearanceDb.EnsureLoaded();
            int job = drawn.Job > 0 ? drawn.Job : look.Job, baseJob = look.Job, sex = look.Sex;
            string sx = RoNames.Sex(sex);
            // the race folder: the drawn class's own (a mount of a Doram class is a Doram class), unless a costume outfit of a Doram
            // exists in the Doram folder (도람족\몸통\*\결혼 / 여름 / 한복 in the GRF)
            bool doram = RoNames.IsDoram(job);
            if (!doram && drawn.Doram && job != baseJob && RoNames.IsPlayer(job))
            {
                string dp = RoNames.BodyPath(job, sex, true);
                if (dp != null && a.SpriteExists(dp)) doram = true;
            }
            string race = doram ? RoNames.Doram : RoNames.Human;

            // ---- body (§3.1); BODY2 = 1 → costume_1 outfit (roBrowserLegacy EntityView.js UpdateBodyStyle + DBManager.js:1198-1215)
            string body = null; int costumeJob = 0;
            if (look.Body2 > 0)
            {
                costumeJob = AppearanceDb.CostumeJob(job);
                string cname = costumeJob > 0 ? AppearanceDb.CostumeBodyName(costumeJob) : null;
                if (cname != null)
                {
                    string c = $"data\\sprite\\{race}\\{RoNames.Body}\\{sx}\\costume_1\\{cname}_{sx}_1";
                    if (a.SpriteExists(c)) body = c; else { Missing("costume body", c); costumeJob = 0; }
                }
                else costumeJob = 0;
            }
            if (body == null && drawn.BodyName != null)
            {
                // w4units: a body name replacing the class's own (a coloured dragon, UnitLooks.DragonBody); missing → the class's body
                string ob = $"data\\sprite\\{race}\\{RoNames.Body}\\{sx}\\{drawn.BodyName}_{sx}";
                if (a.SpriteExists(ob)) body = ob; else Missing("body", ob);
            }
            body ??= RoNames.BodyPath(job, sex, doram);
            Color32[] bodyPal = look.ClothesColor > 0 ? FirstPalette(a, BodyPaletteCandidates(baseJob, sx, look.ClothesColor, doram, costumeJob)) : null;
            if (body != null && a.Sprite(body, out var bspr, out var bact)) s.SetBody(bspr, bact, bodyPal);
            else s.SetBody(null, null);
            s.BodyPath = body; // w4units: diagnostics

            // ---- hair (§3.2) + hair colour (§3.7, used only when > 0: rb EntityView.js:644-658); the orc head (w4units: e_option ORCISH,
            //      roBrowserLegacy DBManager.js:1320-1324 getHeadPath → 이팩트\orcface, no hair palette)
            int headJob = doram == RoNames.IsDoram(job) ? job : baseJob; // the head follows the body's race folder (a Doram in its Doram outfit)
            string head = drawn.Orcish ? UnitLooks.OrcHead : RoNames.HeadPath(look.Hair, headJob, sex);
            Color32[] hairPal = null;
            if (look.HairColor > 0 && !drawn.Orcish)
            {
                int idx = RoNames.HairIndex(look.Hair, headJob, sex);
                string hp = doram
                    ? $"data\\palette\\{RoNames.Doram}\\{HairPal}\\{HairPal}{idx}_{sx}_{look.HairColor}.pal"
                    : $"data\\palette\\{HairPal}\\{HairPal}{idx}_{sx}_{look.HairColor}.pal";
                if (a.Exists(hp)) hairPal = a.Palette(hp);
            }
            if (a.SpriteExists(head) && a.Sprite(head, out var hspr, out var hact)) s.SetHead(hspr, hact, hairPal);
            else { s.SetHead(null, null); Missing("hair", head); }

            // ---- headgears (§3.3) with roBrowserLegacy's duplicate suppression (EntityRender.js:463-485)
            int bottom = look.HeadBottom, mid = look.HeadMid, top = look.HeadTop;
            if (mid == bottom) mid = 0;
            if (top == bottom || top == mid) top = 0;
            SetHeadgear(s, a, ActorSprite.Slot.HeadBottom, bottom, sex);
            SetHeadgear(s, a, ActorSprite.Slot.HeadMid, mid, sex);
            SetHeadgear(s, a, ActorSprite.Slot.HeadTop, top, sex);

            // ---- weapon / shield / left-hand weapon (§1 packing, §3.4, §3.5)
            ApplyHands(s, a, look, job, sx, race);

            // ---- garment (§3.6)
            ApplyRobe(s, a, look.Robe, job, sx, doram);
        }

        private static IEnumerable<string> BodyPaletteCandidates(int job, string sx, int n, bool doram, int costumeJob)
        {
            string p1 = AppearanceDb.PalName(job), p2 = AppearanceDb.PalName2(job);
            if (costumeJob > 0)
            {
                // grf naming: data\palette\몸\costume_1\<PALNAME>_<sex>_<n>_1.pal (794 files); rb PalNameTable[*_2ND] = "costume_1/<name>"
                string pc = AppearanceDb.PalName(costumeJob);
                if (pc != null) yield return $"data\\palette\\{BodyPal}\\{pc}_{sx}_{n}_1.pal";
                if (p1 != null) yield return $"data\\palette\\{BodyPal}\\costume_1\\{p1}_{sx}_{n}_1.pal";
                yield break; // a normal palette does not fit the costume sprite; missing → the sprite's own palette
            }
            if (doram)
            {
                // grf only has data\palette\도람족\body\<PALNAME>_<sex>_<n>.pal (appearance_layers.md §3.7)
                if (p1 != null) yield return $"data\\palette\\{RoNames.Doram}\\body\\{p1}_{sx}_{n}.pal";
                if (p2 != null && p2 != p1) yield return $"data\\palette\\{RoNames.Doram}\\body\\{p2}_{sx}_{n}.pal";
                yield break;
            }
            // rb getBodyPalPath (DBManager.js:1305-1311), then zrenderer's job_pal_names
            if (p1 != null) yield return $"data\\palette\\{BodyPal}\\{p1}_{sx}_{n}.pal";
            if (p2 != null && p2 != p1) yield return $"data\\palette\\{BodyPal}\\{p2}_{sx}_{n}.pal";
        }

        private static Color32[] FirstPalette(RoAssets a, IEnumerable<string> candidates)
        {
            foreach (var p in candidates) if (a.Exists(p)) return a.Palette(p);
            return null; // rb EntityRender.js:787-788: no palette file → the sprite's own palette
        }

        private static void SetHeadgear(ActorSprite s, RoAssets a, ActorSprite.Slot slot, int view, int sex)
        {
            if (view <= 0) { s.ClearPart(slot); return; }
            string p = RoNames.HeadgearPath(view, sex);
            if (p != null && a.SpriteExists(p) && a.Sprite(p, out var spr, out var act)) { s.SetPart(slot, spr, act, null, view); return; }
            s.ClearPart(slot);
            Missing("headgear", p ?? ("view " + view));
        }

        /// <summary>"data\sprite\<race>\<folder>\<prefix>_<sex>" for each weapon class folder candidate of the job.</summary>
        private static void WeaponPrefixes(int job, string sx, string race, List<string> into)
        {
            into.Clear();
            string w1 = AppearanceDb.WeaponJob(job), w2 = AppearanceDb.WeaponJob2(job);
            if (w1 != null) into.Add($"data\\sprite\\{race}\\{w1}\\{w1}_{sx}");   // rb WeaponJobTable (folder = prefix)
            if (w2 != null)                                                        // zrenderer job_weapon_names "folder\prefix"
            {
                string p = $"data\\sprite\\{race}\\{w2}_{sx}";
                if (!into.Contains(p)) into.Add(p);
            }
            if (into.Count == 0 && AppearanceDb.WeaponJob(0) is string w0) into.Add($"data\\sprite\\{race}\\{w0}\\{w0}_{sx}"); // rb: WeaponJobTable[job] || WeaponJobTable[0]
        }

        /// <summary>Weapon sprite for a right/left-hand wire value, or null. Candidate names, each tried in every class folder:
        /// WeaponNameTable[view]; "_<itemId>" (grf names item-specific sprites by item id, e.g. 검사_남_1530); the base type's
        /// name via Expansion_Weapon_IDs (rb EntityView.js:737-744 fallback / zrenderer GetRealWeaponId).</summary>
        private static string FindWeapon(RoAssets a, List<string> prefixes, int value, int view, out int baseType)
        {
            baseType = AppearanceDb.BaseWeaponType(view);
            string n1 = RoNames.WeaponName(view);
            string n2 = value >= AppearanceDb.WeaponViewMax ? "_" + value : null;
            string n3 = baseType != view ? RoNames.WeaponName(baseType) : null;
            foreach (var n in new[] { n1, n2, n3 })
            {
                if (n == null) continue;
                foreach (var pre in prefixes) { string p = pre + n; if (a.SpriteExists(p)) return p; }
            }
            return null;
        }

        private static void ApplyHands(ActorSprite s, RoAssets a, PlayerLook look, int job, string sx, string race)
        {
            int right = look.Weapon, left = look.Shield;
            // rAthena pc_calcweapontype: only a left-hand weapon → it is the weapon (rb MapEngine/Entity.js:1309-1312 swaps too)
            if (right <= 0 && left > 0 && AppearanceDb.IsWeaponItem(left)) { right = left; left = 0; }

            WeaponPrefixes(job, sx, race, _tmp);
            var prefixes = new List<string>(_tmp);
            string weapon = null, leftWeapon = null; int weaponType = 0;
            int rView = AppearanceDb.WeaponView(right);

            if (left > 0 && AppearanceDb.IsWeaponItem(left) && rView > 0)
            {
                // dual wield: one combined sprite (_단검_단검 …) when the class folder has it (assassin line), else both hands
                int lView = AppearanceDb.WeaponView(left);
                int combo = AppearanceDb.DualWieldView(AppearanceDb.BaseWeaponType(rView), AppearanceDb.BaseWeaponType(lView));
                if (combo > 0) { weapon = FindWeapon(a, prefixes, combo, combo, out weaponType); }
                if (weapon != null) left = 0;
                else
                {
                    leftWeapon = lView > 0 ? FindWeapon(a, prefixes, left, lView, out _) : null;
                    if (leftWeapon == null) Missing("left-hand weapon", $"item {left} view {lView} job {job}");
                    left = 0;
                }
            }
            if (weapon == null && rView > 0)
            {
                weapon = FindWeapon(a, prefixes, right, rView, out weaponType);
                if (weapon == null) Missing("weapon", $"value {right} view {rView} job {job}");
            }

            if (weapon != null && a.Sprite(weapon, out var wspr, out var wact))
            {
                s.SetPart(ActorSprite.Slot.Weapon, wspr, wact, null, rView);
                // slash trail: zrenderer "<weapon>_검광" (item-specific trails exist, e.g. 검사_남_1530_검광), then rb WeaponTrailTable
                string trail = null;
                if (a.SpriteExists(weapon + Slash)) trail = weapon + Slash;
                else
                {
                    string t = AppearanceDb.TrailName(weaponType);
                    if (t != null) foreach (var pre in prefixes) if (a.SpriteExists(pre + t)) { trail = pre + t; break; }
                }
                if (trail != null && a.Sprite(trail, out var tspr, out var tact)) s.SetPart(ActorSprite.Slot.WeaponTrail, tspr, tact, null, rView);
                else s.ClearPart(ActorSprite.Slot.WeaponTrail);
            }
            else { s.ClearPart(ActorSprite.Slot.Weapon); s.ClearPart(ActorSprite.Slot.WeaponTrail); }

            // left hand: second weapon (drawn in the shield slot, rb getShieldPath → getWeaponPath) or a shield
            string shield = leftWeapon;
            if (shield == null && left > 0)
            {
                shield = FindShield(a, left, job, sx);
                if (shield == null) Missing("shield", $"value {left} job {job}");
            }
            if (shield != null && a.Sprite(shield, out var sspr, out var sact)) s.SetPart(ActorSprite.Slot.Shield, sspr, sact, null, left);
            else s.ClearPart(ActorSprite.Slot.Shield);
        }

        /// <summary>data\sprite\방패\<folder>\<folder>_<sex>_<name>: "_<itemId>_방패" first (grf ships item-numbered shields such as
        /// 검사_남_2189_방패, zrenderer resolver.d shieldSprite), then ShieldTable[ClassNum] (rb getShieldPath DBManager.js:2020-2047).
        /// Folders: the body job name first (the grf's transcendent/3rd-class shield files are authored for their own bodies —
        /// 룬나이트_남_가드.act carries the RK anchors while 기사's is 8 px off and mirrored; research/appearance_verification.md),
        /// then rb's WeaponJobTable folder (Royal Guard → 크루세이더, Sura → 몽크), then the folder of zrenderer's weapon table
        /// (rental mounts use their base class there, e.g. 페코검사 → 검사). ClassNum 0 and 5 (books, toys) have no sprite: nothing is drawn.</summary>
        private static string FindShield(RoAssets a, int value, int job, string sx)
        {
            int view = AppearanceDb.ShieldView(value);
            string tbl = view > 0 ? AppearanceDb.ShieldName(view) : null;
            string byId = value >= AppearanceDb.WeaponViewMax ? "_" + value + ShieldSuffix : null;
            string f1 = RoNames.PcName(job), f2 = AppearanceDb.WeaponJob(job) ?? AppearanceDb.WeaponJob(0);
            string w2 = AppearanceDb.WeaponJob2(job);
            int cut = w2 != null ? w2.IndexOf('\\') : -1;
            string f3 = cut > 0 ? w2.Substring(0, cut) : null;
            foreach (var n in new[] { byId, tbl != null ? "_" + tbl : null })
            {
                if (n == null) continue;
                foreach (var f in new[] { f1, f2, f3 })
                {
                    if (f == null) continue;
                    string p = $"data\\sprite\\{Shield}\\{f}\\{f}_{sx}{n}";
                    if (a.SpriteExists(p)) return p;
                }
            }
            return null;
        }

        /// <summary>Garment: act data\sprite\로브\<name>\<sex>\<JOBNAME>_<sex>; spr from the same path, else the shared
        /// data\sprite\로브\<name>\<name>[_doram].spr (rb getRobePath / getRobePathNoSex, EntityView.js:745-755).</summary>
        private static void ApplyRobe(ActorSprite s, RoAssets a, int robe, int job, string sx, bool doram)
        {
            string name = robe > 0 ? RoNames.RobeName(robe) : null;
            if (name == null) { s.ClearPart(ActorSprite.Slot.Robe); if (robe > 0) Missing("garment", "view " + robe); return; }
            string jobName = RoNames.PcName(job) ?? RoNames.PcName(0);
            string actPath = $"data\\sprite\\{RoNames.Robe}\\{name}\\{sx}\\{jobName}_{sx}";
            if (!a.Exists(actPath + ".act")) { s.ClearPart(ActorSprite.Slot.Robe); Missing("garment", actPath); return; }
            string sprPath = actPath;
            if (!a.Exists(sprPath + ".spr"))
            {
                sprPath = $"data\\sprite\\{RoNames.Robe}\\{name}\\{name}{(doram ? "_doram" : "")}";
                if (!a.Exists(sprPath + ".spr")) { s.ClearPart(ActorSprite.Slot.Robe); Missing("garment", sprPath); return; }
            }
            var spr = a.SpriteSpr(sprPath); var act = a.SpriteAct(actPath);
            if (spr != null && act != null) s.SetPart(ActorSprite.Slot.Robe, spr, act, null, robe);
            else s.ClearPart(ActorSprite.Slot.Robe);
        }
