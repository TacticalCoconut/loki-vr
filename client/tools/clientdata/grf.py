r"""
Read-only GRF 0x200 / 0x300 reader, a line-by-line port of the client's own reader
(client/Assets/Loki/Runtime/IO/GrfArchive.cs + GrfCrypt.cs), so client-data tools can read the fresh LATAM install
(C:\\Ragnarok Online\\data.grf, GRF 0x300 "Event Horizon") without Unity.

  python grf.py list    <grf> <regex>                list entries whose name (CP949 decoded) matches
  python grf.py extract <grf> <outdir> <path>...     extract entries (RO paths, any case / slash style) into
                                                     <outdir>\<the entry's own folders>

Names are CP949 bytes in the GRF; lookups here use the same normalisation as RoPath.Normalize (A-Z lower-cased,
'/' -> '\\', bytes >= 0x80 untouched).
"""
import os, re, struct, sys, zlib

HEADER = 46
FLAG_FILE, FLAG_MIXCRYPT, FLAG_DES = 0x01, 0x02, 0x04


def normalize(name: bytes) -> bytes:
    return bytes((c + 32) if 65 <= c <= 90 else (0x5C if c == 0x2F else c) for c in name)


class Grf:
    def __init__(self, path):
        self.path = path
        self.f = open(path, 'rb')
        hdr = self.f.read(HEADER)
        if hdr[:15] != b'Master of Magic' and hdr[:13] != b'Event Horizon':
            raise ValueError('not a GRF: ' + path)
        version = struct.unpack_from('<I', hdr, 42)[0]
        self.version = version & 0xFF00
        if self.version == 0x300:   # GrfArchive.cs ReadTable: 64-bit table offset at 30, count at 38, 4 unknown bytes
            table_at = HEADER + struct.unpack_from('<Q', hdr, 30)[0] + 4
            count = struct.unpack_from('<I', hdr, 38)[0]
        elif self.version == 0x200:
            table_at = HEADER + struct.unpack_from('<I', hdr, 30)[0]
            count = struct.unpack_from('<I', hdr, 38)[0] - struct.unpack_from('<I', hdr, 34)[0] - 7
        else:
            raise ValueError('GRF version 0x%x not supported' % version)
        self.f.seek(table_at)
        packed, unpacked = struct.unpack('<II', self.f.read(8))
        table = zlib.decompress(self.f.read(packed))
        assert len(table) == unpacked, 'table size %d != %d' % (len(table), unpacked)
        self.entries = {}
        p = 0
        for _ in range(count):
            if p >= len(table): break
            e = table.index(b'\0', p)
            name = table[p:e]; p = e + 1
            cs, csa, us = struct.unpack_from('<III', table, p)
            flags = table[p + 12]
            off = struct.unpack_from('<Q' if self.version == 0x300 else '<I', table, p + 13)[0]
            p += 21 if self.version == 0x300 else 17
            if not flags & FLAG_FILE: continue
            self.entries[normalize(name)] = (name, cs, csa, us, flags, off)

    def names(self):
        return [v[0] for v in self.entries.values()]

    def read(self, ro_path):
        key = normalize(ro_path if isinstance(ro_path, bytes) else ro_path.encode('cp949'))
        ent = self.entries.get(key)
        if ent is None: return None
        name, cs, csa, us, flags, off = ent
        self.f.seek(HEADER + off)
        buf = bytearray(self.f.read(csa))
        low = key.lower()
        header_only = low.endswith(b'.gnd') or low.endswith(b'.gat') or low.endswith(b'.act') or low.endswith(b'.str')
        decrypt_entry(flags, cs, buf, header_only)
        if us == cs and not looks_like_zlib(buf):
            return bytes(buf[:us])
        return zlib.decompress(bytes(buf[:cs]))


def looks_like_zlib(b):
    return len(b) >= 2 and (b[0] & 0x0F) == 8 and ((b[0] << 8) | b[1]) % 31 == 0


