#!/usr/bin/env python3
"""
Builds Assets/StreamingAssets/data/appearance.txt and itemviews.tsv (player equipment look-up tables).
See README.md in this folder for the full pipeline and where every table comes from.

usage: build_appearance.py <rb_tables.json> <lubs.tsv> <zrenderer resolver_data dir>
                           <classnum_new.tsv> <classnum_old.tsv> <rathena db dir> <out dir>

appearance.txt  (Latin-1 text holding CP949 bytes, exactly like spritenames.txt; tab separated; '#' = comment)
  wjob  <job> <folder>          roBrowserLegacy WeaponJobTable: weapon/shield class folder and file prefix
  wjob2 <job> <folder\\prefix>  zrenderer job_weapon_names.txt (fallback folder when the first has no file)
  pal   <job> <name>            roBrowserLegacy PalNameTable: clothes palette base name ('/' written as '\\')
  pal2  <job> <name>            zrenderer job_pal_names.txt (fallback)
  shield <view> <name>          roBrowserLegacy Items/ShieldTable.js (shield ClassNum -> file suffix)
  trail <weaponType> <suffix>   roBrowserLegacy Items/WeaponTrailTable.js ("_<type>_<slash>")
  wexp  <view> <baseType>       client weapontable.lub Expansion_Weapon_IDs (item-specific view -> base type)
  costume <job> <costumeJob>    roBrowserLegacy EntityView.js getBodyVal(): 3rd/4th job -> *_2ND costume id
  costumename <costumeJob> <bodyName>   body file name of that costume id (JobNameTable duplicate of the 3rd job)
  watk <job> <sex|-1> <weaponType> <0|1|2>   roBrowserLegacy DB/Jobs/WeaponAction.js: PC attack motion per weapon type
                                        (0/1/2 = ATTACK1/ATTACK2/ATTACK3 = action groups 5/10/11); sex -1 = both
  layerdef <Mid|Top|Bottom|Robe> <n>    client tb_layer_priority.lub TB_Layer_Priority.Default_*
  layer <accViewId> <default|-> <dir=n,...>  TB_Layer_Priority.Items_List

itemviews.tsv   (ASCII, tab separated, no header)
  id, type (rAthena item Type: 4 armor, 5 weapon, -1 not in rAthena), classNum (client item table ClassNum,
  -1 when the item is in neither client table), weaponType (rAthena weapon SubType as W_* number, -1 if none),
  leftHand (1 when rAthena Locations has Left_Hand, i.e. a shield for armor)
  Only rows with type 4/5 or a non-zero ClassNum are written.
"""
import json, os, sys, yaml

# rAthena src/map/pc.hpp enum weapon_type; item_db SubType "X" is looked up as script constant "W_X" (itemdb.cpp:161)
W = {'FIST': 0, 'DAGGER': 1, '1HSWORD': 2, '2HSWORD': 3, '1HSPEAR': 4, '2HSPEAR': 5, '1HAXE': 6, '2HAXE': 7, 'MACE': 8,
     '2HMACE': 9, 'STAFF': 10, 'BOW': 11, 'KNUCKLE': 12, 'MUSICAL': 13, 'WHIP': 14, 'BOOK': 15, 'KATAR': 16,
     'REVOLVER': 17, 'RIFLE': 18, 'GATLING': 19, 'SHOTGUN': 20, 'GRENADE': 21, 'HUUMA': 22, '2HSTAFF': 23}
ADVANCED_JOB_INDEX = 3950  # zrenderer source/resolver.d:76 (row index = job id - 3950 for job ids > 4000)


def lat(h):
    """hex of CP949 bytes -> Latin-1 string (byte-exact, as RoNames/AppearanceDb read the file)"""
    return bytes.fromhex(h).decode('latin-1')


def zr_rows(path):
    rows = {}
    lines = open(path, encoding='utf-8').read().split('\n')
    for i, s in enumerate(lines):
        s = s.strip()
        if not s:
            continue
        if i <= 45:
            job = i
        elif i >= 51:
            job = i + ADVANCED_JOB_INDEX
        else:
            continue  # rows 46..50 would be job ids 46..50 (not player classes)
        rows[job] = s.encode('cp949').decode('latin-1')
    return rows


def main(rb_json, lubs_tsv, zr_dir, cn_new, cn_old, rathena_db, outdir):
    rb = json.load(open(rb_json))
    out = []
    out.append('# Loki appearance tables. Encoding: Latin-1 (CP949 bytes preserved). Generated by tools/appearance/build_appearance.py.')
    for kind, key in (('wjob', 'weaponjob'), ('pal', 'palname'), ('shield', 'shield'), ('trail', 'trail')):
        for k in sorted(rb[key], key=int):
            v = lat(rb[key][k]).replace('/', '\\')
            out.append(f'{kind}\t{k}\t{v}')
    for kind, fn in (('wjob2', 'job_weapon_names.txt'), ('pal2', 'job_pal_names.txt')):
        for job, v in sorted(zr_rows(os.path.join(zr_dir, fn)).items()):
            out.append(f'{kind}\t{job}\t{v}')
    for k in sorted(rb['costume'], key=int):
        out.append(f'costume\t{k}\t{rb["costume"][k]}')
    for k in sorted(rb['costumeName'], key=int):
        out.append(f'costumename\t{k}\t{lat(rb["costumeName"][k])}')
    for job in sorted(rb['weaponAction'], key=int):
        for sex, wt, idx in rb['weaponAction'][job]:
            out.append(f'watk\t{job}\t{sex}\t{wt}\t{idx}')
    for line in open(lubs_tsv, encoding='ascii'):
        line = line.rstrip('\n')
        if line:
            out.append(line)
    with open(os.path.join(outdir, 'appearance.txt'), 'w', encoding='latin-1', newline='\n') as f:
        f.write('\n'.join(out) + '\n')

    # ---- itemviews.tsv
    def classnums(p):
        d = {}
        for line in open(p, encoding='ascii'):
            a, b = line.rstrip('\n').split('\t')
            d[int(a)] = int(b)
        return d
    new, old = classnums(cn_new), classnums(cn_old)
    cn = dict(old)
    cn.update(new)  # iteminfo_new (the table items.tsv is built from) wins; itemInfo.lua fills the items it lacks
    typ, sub, left = {}, {}, {}
    TYPES = {'Armor': 4, 'Weapon': 5}
    d = yaml.safe_load(open(os.path.join(rathena_db, 're', 'item_db_equip.yml'), encoding='utf-8'))
    for it in d.get('Body') or []:
        t = TYPES.get(it.get('Type'))
        if t is None:
            continue
        iid = it['Id']
        typ[iid] = t
        if t == 5:
            st = str(it.get('SubType', 'Fist')).upper()
            sub[iid] = W.get(st, 0)
        loc = it.get('Locations') or {}
        left[iid] = 1 if loc.get('Left_Hand') else 0
    ids = sorted(set(typ) | {i for i, c in cn.items() if c})
    n = 0
    with open(os.path.join(outdir, 'itemviews.tsv'), 'w', encoding='ascii', newline='\n') as f:
        for i in ids:
            f.write(f'{i}\t{typ.get(i, -1)}\t{cn.get(i, -1)}\t{sub.get(i, -1)}\t{left.get(i, 0)}\n')
            n += 1
    print('appearance rows', len(out), 'itemviews', n, 'classnum new', len(new), 'old', len(old))


if __name__ == '__main__':
    main(*sys.argv[1:])
