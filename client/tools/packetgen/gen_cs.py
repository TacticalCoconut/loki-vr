#!/usr/bin/env python3
"""Generates Assets/Loki/Runtime/Net/PacketTable.g.cs from the rAthena dumps (map table + login/char headers)."""
import json, sys
mp = json.load(open('packets_20211103.json'))
cm = json.load(open('common_20211103.json'))
lens = {}
funcs = {}
for p in mp['packets']:            # last registration wins, like packetdb_addpacket
    lens[p['id']] = p['len']
    if p['func']: funcs[p['id']] = p['func']
# Server→client packets are sent as sizeof(struct) / packetLength, and most are NOT in packetdb: merge the struct sizes
# (sizes_20211103.json from dump3.cpp). Struct wins over packetdb except for client→server (CZ_) structs.
for s in json.load(open('sizes_20211103.json'))['sizes']:
    if s['name'].startswith('PACKET_CZ_'): continue
    lens[s['id']] = -1 if s['dyn'] else s['size']
# Structs whose id comes from the packet_headers enum (packets_struct.hpp) rather than DEFINE_PACKET_HEADER, so dump3 missed them:
# sizes_extra.json, measured with a g++ probe against the headers at PACKETVER 20211103 (party 0x0ae4/0x0ae5, guild leave/expel 0x0a82/0x0a83).
for s in json.load(open('sizes_extra.json'))['sizes']:
    if s['name'].startswith('PACKET_CZ_'): continue
    lens[s['id']] = -1 if s['dyn'] else s['size']
# dump3.cpp flagged variable-length structs by their length field's name and missed the four that call it `packetSize`
# (all end in a flexible array member; rAthena packets.hpp: ZC_WHISPER_LIST 2076-2085, ZC_ROOM_NEWENTRY 1700-1710,
# ZC_ENTER_ROOM 1092-1103, ZC_CHANGE_CHATROOM 988-998). The client must read their u16 length at offset 2.
for k in (0x00d4, 0x00d7, 0x00db, 0x00df): lens[k] = -1
# Packets written with raw WFIFOW/WFIFOSET(fd, <literal>) and never registered anywhere (raw_sizes.json, scanned from src/map/*.cpp).
for k, v in json.load(open('raw_sizes.json')).items():
    k = int(k)
    if k < 0x2af8 and k not in lens: lens[k] = v
# Variable-length WFIFO packets that no table above covers (raw_dynamic.json).
for k, v in json.load(open('raw_dynamic.json'))['ids'].items():
    k = int(k, 16)
    if k not in lens: lens[k] = v
# login/char server packets (from src/common/packets.hpp struct sizes; -1 = has packetLength field)
S = cm['structs']; H = cm['headers']
common = {
    H['CA_LOGIN']: S['PACKET_CA_LOGIN'], H['AC_ACCEPT_LOGIN']: -1, H['AC_REFUSE_LOGIN']: S['PACKET_AC_REFUSE_LOGIN'],
    0x65: 17, H['HC_ACCEPT_ENTER']: -1, H['HC_ACCEPT_ENTER2']: -1, H['HC_REFUSE_ENTER']: S['PACKET_HC_REFUSE_ENTER'],
    H['HC_CHARLIST_NOTIFY']: S['PACKET_HC_CHARLIST_NOTIFY'], H['CH_CHARLIST_REQ']: 2, H['HC_ACK_CHARINFO_PER_PAGE']: -1,
    H['HC_BLOCK_CHARACTER']: -1, H['HC_SECOND_PASSWD_LOGIN']: S['PACKET_HC_SECOND_PASSWD_LOGIN'],
    H['CH_SELECT_CHAR']: S['PACKET_CH_SELECT_CHAR'], H['HC_NOTIFY_ZONESVR']: S['PACKET_HC_NOTIFY_ZONESVR'],
    H['CH_MAKE_CHAR']: S['PACKET_CH_MAKE_CHAR'], H['HC_ACCEPT_MAKECHAR']: S['PACKET_HC_ACCEPT_MAKECHAR'], H['HC_REFUSE_MAKECHAR']: S['PACKET_HC_REFUSE_MAKECHAR'],
    H['HC_NOTIFY_ACCESSIBLE_MAPNAME']: -1, H['SC_NOTIFY_BAN']: 3, H['PING']: 6, H['HC_ACK_IS_VALID_CHARNAME']: 4,
    H['HC_ACCEPT_DELETECHAR']: 2, H['HC_REFUSE_DELETECHAR']: 3, H['TC_RESULT']: -1, H['AC_ACK_HASH']: -1,
    # deletion replies: packets.hpp:485-518 (id.W CID.L result.L [date.L]) — not in the struct dump
    H['HC_DELETE_CHAR3_RESERVED']: 14, H['HC_DELETE_CHAR3']: 10, H['HC_DELETE_CHAR3_CANCEL']: 10,
    # rename / slot move replies (client wave 1): common/packets.hpp:440-452 HC_ACK_CHANGE_CHARNAME id.W result.L (PACKETVER >= 20111101)
    # and :595-611 HC_ACK_CHANGE_CHARACTER_SLOT id.W packetLength.W reason.W moves.W (0x0b70 for PACKETVER_RE_NUM >= 20211103)
    H['HC_ACK_CHANGE_CHARNAME']: 6, H['HC_ACK_CHANGE_CHARACTER_SLOT']: -1,
}
out = []
out.append('// <auto-generated> by tools/packetgen/gen_cs.py from rAthena %s headers (PACKETVER %d). Do not edit. </auto-generated>' % ('e985006', mp['packetver']))
out.append('using System.Collections.Generic;')
out.append('namespace Loki.Net {')
out.append('public static partial class PacketTable {')
out.append('    public const int PacketVer = %d;' % mp['packetver'])
out.append('    public const int CharacterInfoSize = %d;' % S['CHARACTER_INFO'])
out.append('    /// <summary>Map-server packet lengths (-1 = variable, u16 length at offset 2). Last registration wins, like rAthena.</summary>')
out.append('    public static readonly Dictionary<ushort, short> MapLengths = new Dictionary<ushort, short>(%d) {' % len(lens))
out.append('        ' + ', '.join('{0x%04x,%d}' % (k, v) for k, v in sorted(lens.items())))
out.append('    };')
out.append('    /// <summary>Login/char-server packet lengths.</summary>')
out.append('    public static readonly Dictionary<ushort, short> CommonLengths = new Dictionary<ushort, short>(%d) {' % len(common))
out.append('        ' + ', '.join('{0x%04x,%d}' % (k, v) for k, v in sorted(common.items())))
out.append('    };')
out.append('    /// <summary>rAthena parser bound to each client→server packet id (documentation only).</summary>')
out.append('    public static readonly Dictionary<ushort, string> ClientPacketParsers = new Dictionary<ushort, string>(%d) {' % len(funcs))
out.append('        ' + ', '.join('{0x%04x,"%s"}' % (k, v) for k, v in sorted(funcs.items())))
out.append('    };')
out.append('    public static class Common {')
for k, v in sorted(H.items()): out.append('        public const ushort %s = 0x%04x;' % (k, v))
out.append('    }')
out.append('}}')
# UTF-8 and LF on every OS (the table carries → in its comments; on Windows the default would be cp1252 and CRLF)
open(sys.argv[1] if len(sys.argv) > 1 else 'PacketTable.g.cs', 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('wrote', len(lens), 'map ids,', len(common), 'common ids')
