#!/usr/bin/env python3
"""Reference vectors for Loki's IMA ADPCM voice codec (client wave 6, w6voice).

Runs the test signals through CPython's own Intel/DVI (IMA) ADPCM coder, audioop.lin2adpcm / adpcm2lin
(Modules/audioop.c; the module exists up to Python 3.12), and writes them as a C# table that
tools/lokihost/Tests/VoiceTests.cs compares Loki's codec with, byte for byte.

    python3 client/tools/voice/adpcm_reference.py > tools/lokihost/Tests/AdpcmReference.g.cs

(On this PC: the WSL distro "Loki" has Python 3.12; Windows' Python 3.13 / 3.14 no longer ship audioop.)

Each vector is 640 samples (two 20 ms frames at 16 kHz), 16-bit. The coder starts as Loki's encoder starts a talk
spurt: predictor = the first sample, step index 0. audioop packs the earlier sample of a pair into the HIGH nibble;
Loki's frames (and Microsoft's IMA WAVE blocks) use the LOW nibble: the test swaps the nibbles.
"""
import audioop
import math
import struct
import sys

N = 640


def clamp(v):
    return max(-32768, min(32767, int(v)))


def sine(freq, amp):
    return [clamp(round(amp * math.sin(2 * math.pi * freq * i / 16000.0))) for i in range(N)]


def lcg_noise(amp, seed=12345):
    out, x = [], seed
    for _ in range(N):
        x = (x * 1103515245 + 12345) & 0x7FFFFFFF
        out.append(clamp(((x >> 8) & 0xFFFF) - 32768) * amp // 32768)
    return out


def speechlike():
    # a 140 Hz "voice": harmonics with a formant-like weighting, under a syllable envelope
    out = []
    for i in range(N):
        t = i / 16000.0
        env = 0.5 - 0.5 * math.cos(2 * math.pi * t / 0.04)
        s = sum(math.sin(2 * math.pi * 140 * h * t) * w for h, w in ((1, 0.5), (2, 0.9), (4, 1.0), (5, 0.7), (9, 0.4), (17, 0.25), (24, 0.15)))
        out.append(clamp(round(6000 * env * s)))
    return out


def square(amp, period):
    return [amp if (i // period) % 2 == 0 else -amp for i in range(N)]


VECTORS = [
    ("sine 440 Hz, amplitude 8000", sine(440, 8000)),
    ("sine 3000 Hz, amplitude 20000", sine(3000, 20000)),
    ("speech-like harmonics of 140 Hz", speechlike()),
    ("noise, full scale", lcg_noise(32768)),
    ("square wave +-32767, period 40 (overload)", square(32767, 20)),
    ("silence", [0] * N),
]


def main():
    print("// Generated by client/tools/voice/adpcm_reference.py with Python %d.%d's audioop (lin2adpcm / adpcm2lin): do not edit." % sys.version_info[:2])
    print("namespace LokiHost.Tests;")
    print()
    print("/// <summary>IMA ADPCM reference vectors from CPython's audioop: 640 samples each; the coder starts at (first sample, index 0);")
    print("/// Adpcm is audioop's packing (the earlier sample in the high nibble).</summary>")
    print("public static class AdpcmReference")
    print("{")
    print("    public sealed record Vector(string Name, string PcmHex, string AdpcmHex, string DecodedHex, int EndPredictor, int EndIndex);")
    print("    public static readonly Vector[] Vectors =")
    print("    {")
    for name, pcm in VECTORS:
        raw = struct.pack("<%dh" % N, *pcm)
        state = (pcm[0], 0)
        adpcm, end = audioop.lin2adpcm(raw, 2, state)
        decoded, end2 = audioop.adpcm2lin(adpcm, 2, state)
        assert end == end2, (end, end2)
        print('        new("%s", "%s", "%s", "%s", %d, %d),' % (name, raw.hex(), adpcm.hex(), decoded.hex(), end[0], end[1]))
    print("    };")
    print("}")


if __name__ == "__main__":
    main()
