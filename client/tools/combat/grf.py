def _rotl(v, n): return ((v << n) | (v >> (64 - n))) & M64


def _delta_swap(a, delta, mask):
    b = (a ^ (a >> delta)) & mask
    return (a ^ b ^ (b << delta)) & M64


def _ip(m):
    m = _delta_swap(m, 9, 0x0055005500550055); m = _delta_swap(m, 18, 0x0000333300003333)
    m = _delta_swap(m, 36, 0x000000000F0F0F0F); m = _delta_swap(m, 24, 0x00000000FF00FF00)
    return _delta_swap(m, 24, 0x000000FF000000FF)


def _fp(m):
    m = _delta_swap(m, 24, 0x000000FF000000FF); m = _delta_swap(m, 24, 0x00000000FF00FF00)
    m = _delta_swap(m, 36, 0x000000000F0F0F0F); m = _delta_swap(m, 18, 0x0000333300003333)
    return _delta_swap(m, 9, 0x0055005500550055)


def _expand(b):
    return (((b << 31) & 0x8000000000000000) | ((b >> 1) & 0x7C00000000000000) | ((b >> 3) & 0x03F0000000000000) |
            ((b >> 5) & 0x000FC00000000000) | ((b >> 7) & 0x00003F0000000000) | ((b >> 9) & 0x000000FC00000000) |
            ((b >> 11) & 0x00000003F0000000) | ((b >> 13) & 0x000000000FC00000) | ((b >> 15) & 0x00000000003E0000) |
            ((b >> 47) & 0x0000000000010000))


def _sbox(x):
    out = 0
    for i in range(8): out |= _S[i][(x >> (58 - i * 6)) & 0x3F] << (60 - i * 4)
    return out


def _pbox(block):
    block = _rotl(block, 44)
    b1 = (block & 0x0000000000200000) << 32
    b2 = (block & 0x0000000000480000) << 13
    b3 = (block & 0x0000088000000000) << 12
    b4 = (block & 0x0000002020120000) << 25
    b5 = (block & 0x0000000442000000) << 14
    b6 = (block & 0x0000000001800000) << 37
    b7 = (block & 0x0000000004000000) << 24
    b8 = (((block & 0x0000020280015000) * 0x0000020080800083) & M64) & 0x02000A6400000000
    b9 = (((_rotl(block, 29) & 0x01001400000000AA) * 0x0000210210008081) & M64) & 0x0902C01200000000
    b10 = (((block & 0x0000000910040000) * 0x0000000C04000020) & M64) & 0x8410010000000000
    return (b1 | b2 | b3 | b4 | b5 | b6 | b7 | b8 | b9 | b10) & M64


def _round(inp):
    left = inp & (0xFFFFFFFF << 32)
    right = (inp << 32) & M64
    return (right | ((_pbox(_sbox(_expand(right))) ^ left) >> 32)) & M64


def decode_des_block(block):
    return _fp(_rotl(_round(_ip(block)), 32))  # Gravity swapped the halves


