fn sorted(v: &[i32]) -> Vec<i32> {
    let mut v = v.to_vec();
    v.sort();
    v
}

#[test]
fn switches_have_rathenas_cases() {
    assert_eq!(sorted(super::sc_immune::CASES), sorted(R_IMMUNITY), "immunity switch");
    let mut vals: Vec<i32> = Vec::new();
    for part in [super::sc_vals_a::CASES, super::sc_vals_b::CASES, super::sc_vals_c::CASES] {
        for &t in part {
            assert!(!vals.contains(&t), "status {t} has a value case in two parts");
            vals.push(t);
        }
    }
    assert_eq!(sorted(&vals), sorted(R_VALS), "value setup switch");
    assert_eq!(sorted(super::sc_end_fx::CASES), sorted(R_END), "end-effect switch");
    assert_eq!(sorted(super::sc_timer_fx::CASES), sorted(R_TIMER), "timer switch");
    assert_eq!(sorted(super::sc_clear::CASES_TIMER_SUB), sorted(R_TIMER_SUB), "status_change_timer_sub");
}
