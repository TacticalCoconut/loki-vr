#!/usr/bin/env python3
"""Generates src/status/consts.rs: status.hpp `enum sc_type`, `enum efst_type`, `enum e_scb_flag`, `enum e_scs_flag`,
`enum e_status_change_flag` and map.hpp `enum _sp`, with the values the compiler gives them (sequential numbering,
explicit and symbolic assignments). Cross-checked against tools/script_constants.tsv where both name a constant.

  python3 tools/gen_status_consts.py <rathena-src> src/status/consts.rs
"""
import re, sys

def strip_comments(s):
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    return re.sub(r'//[^\n]*', '', s)

def parse_enum(text, name):
    m = re.search(r'enum\s+' + re.escape(name) + r'\b[^{]*\{(.*?)\n\};', text, re.S)
    if not m:
        raise SystemExit(f'enum {name} not found')
    body = strip_comments(m.group(1))
    vals, out, nxt = {}, [], 0
    for item in body.split(','):
        item = item.strip()
        if not item:
            continue
        if '=' in item:
            k, v = [x.strip() for x in item.split('=', 1)]
            expr = v
            for kk in sorted(vals, key=len, reverse=True):
                expr = re.sub(r'\b' + kk + r'\b', str(vals[kk]), expr)
            val = int(eval(expr))
        else:
            k, val = item, nxt
        vals[k] = val
        out.append((k, val))
        nxt = val + 1
    return out

src = sys.argv[1]
status_hpp = open(f'{src}/src/map/status.hpp').read()
map_hpp = open(f'{src}/src/map/map.hpp').read()
enums = [
    ('sc_type', status_hpp, 'i32', 'status.hpp enum sc_type'),
    ('efst_type', status_hpp, 'i32', 'status.hpp enum efst_type'),
    ('e_scb_flag', status_hpp, 'u32', 'status.hpp enum e_scb_flag'),
    ('e_scs_flag', status_hpp, 'u32', 'status.hpp enum e_scs_flag'),
    ('e_status_change_flag', status_hpp, 'u32', 'status.hpp enum e_status_change_flag'),
    ('_sp', map_hpp, 'i32', 'map.hpp enum _sp'),
]
tsv = {}
for line in open('tools/script_constants.tsv'):
    p = line.rstrip('\n').split('\t')
    if len(p) >= 2:
        try:
            tsv[p[0]] = int(p[1])
        except ValueError:
            pass
lines = ['//! Generated by tools/gen_status_consts.py from rAthena e985006 headers (status.hpp, map.hpp). Do not edit.',
         '//! Values checked against the compiler (tools/script_constants.tsv) for every name it exports.', '',
         '#![allow(dead_code, non_upper_case_globals)]', '']
bad = 0
for name, text, ty, doc in enums:
    lines.append(f'// {doc}')
    seen = set()
    for k, v in parse_enum(text, name):
        if k in tsv and tsv[k] != v:
            print(f'MISMATCH {k}: parsed {v}, compiler {tsv[k]}', file=sys.stderr)
            bad += 1
        if k in seen:
            continue
        seen.add(k)
        lines.append(f'pub const {k}: {ty} = {v};')
    lines.append('')
open(sys.argv[2], 'w', newline='\n').write('\n'.join(lines))

# The status changes that have their own case in status.cpp's big per-SC switches (e985006 line ranges): the status
# framework runs the ported cases and reports the others as not ported yet (phase 4) instead of guessing their effect.
cpp = open(f'{src}/src/map/status.cpp').read().split('\n')
# The build's preprocessor switches (config/renewal.hpp: all renewal defines on; PACKETVER 20211103): a case label
# inside `#ifndef RENEWAL` or `#ifndef RENEWAL_ASPD` is not compiled, so it is not listed (audit status 4.3 / 4.4).
DEFINED = {'RENEWAL', 'RENEWAL_CAST', 'RENEWAL_DROP', 'RENEWAL_EXP', 'RENEWAL_LVDMG', 'RENEWAL_ASPD'}
PACKETVER = 20211103
def cond(expr):
    m = re.fullmatch(r'PACKETVER\s*(<|>=|>|<=|==|!=)\s*(\d+)', expr)
    if m:
        return eval(f'{PACKETVER} {m.group(1)} {m.group(2)}')
    m = re.fullmatch(r'defined\s*\(?\s*(\w+)\s*\)?', expr)
    if m:
        return m.group(1) in DEFINED
    raise SystemExit(f'gen_status_consts: unknown #if expression {expr!r}')
def active_lines(a, b):
    """The lines a..b (1-based) the preprocessor keeps; directive lines and dropped lines give ''."""
    out, stack, active = [], [], True
    for l in cpp[a - 1:b]:
        m = re.match(r'\s*#\s*(ifdef|ifndef|if|elif|else|endif)\b(.*)', l)
        if not m:
            out.append(l if active else '')
            continue
        d, rest = m.group(1), re.sub(r'//.*|/\*.*?\*/', '', m.group(2)).strip()
        if d in ('ifdef', 'ifndef', 'if'):
            c = (rest in DEFINED) if d == 'ifdef' else (rest not in DEFINED) if d == 'ifndef' else cond(rest)
            stack.append([active, c])
            active = active and c
        elif d == 'elif':
            parent, taken = stack[-1]
            c = not taken and cond(rest)
            stack[-1][1] = taken or c
            active = parent and c
        elif d == 'else':
            parent, taken = stack[-1]
            stack[-1][1] = True
            active = parent and not taken
        else:
            active = stack.pop()[0]
        out.append('')
    if stack:
        raise SystemExit(f'gen_status_consts: unbalanced #if in lines {a}-{b}')
    return out
def cases(a, b, depth):
    pat = re.compile(r'^' + '\t' * depth + r'case (SC_\w+)\s*:')
    names = []
    for l in active_lines(a, b):
        m = pat.match(l)
        if m and m.group(1) not in names:
            names.append(m.group(1))
    return names
all_sc = dict(parse_enum(status_hpp, 'sc_type'))
extra = ['', '// status.cpp per-SC switch case labels (see tools/gen_status_consts.py)']
for name, (a, b, depth) in [('SC_IMMUNITY_CASES', (10317, 10661, 2)), ('SC_START_VAL_CASES', (10813, 13025, 2)),
                            ('SC_END_CASES', (13519, 14031, 2)), ('SC_TIMER_CASES', (14143, 15215, 1))]:
    lst = cases(a, b, depth)
    vals = sorted(all_sc[n] for n in lst)
    extra.append(f'pub const {name}: &[i32] = &[{", ".join(str(v) for v in vals)}];')
with open(sys.argv[2], 'a', newline='\n') as f:
    f.write('\n'.join(extra) + '\n')

print(f'wrote {sys.argv[2]}; {bad} mismatches')
sys.exit(1 if bad else 0)
