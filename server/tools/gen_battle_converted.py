"""Writes src/battle_config/converted.rs and prints the lists of server/ARCHITECTURE.md (section 3). Run from server/:

    python tools/gen_battle_converted.py

A member is CONVERTED when it has a run-time reader (a `get(Bc::X)` outside battle_config/, a
`battle_get_value("name")`, or it is one of battle_config/mod.rs MOBDB_MEMBERS), no constant is left for it anywhere
(a `const NAME` whose name is the member's or the setting's), and datagen does not bake it into another dataset (the
BAKED list below: keep it in step with tools/datagen_mods). PARTIAL_BAKED: readers, but baked too. CONST_ONLY: a
constant and no reader. REST: neither.
"""
import os
import re

data = open('src/battle_config/data.rs', encoding='utf-8').read()
members = {}   # member -> (ident, index, setting name)
for m in re.finditer(r'/// `([^`]+)` \(battle_config\.(\w+), [^)]*\)\.\n\s+pub const (\w+): Bc = Bc\((\d+)\);', data):
    members[m.group(2)] = (m.group(3), int(m.group(4)), m.group(1))
by_ident = {v[0]: (k, v[1], v[2]) for k, v in members.items()}
names = {v[2].replace('.', '_'): k for k, v in members.items()}

texts = {}
for root, _, fs in os.walk('src'):
    for f in fs:
        if f.endswith('.rs'):
            p = os.path.join(root, f).replace(os.sep, '/')
            texts[p] = open(p, encoding='utf-8').read()

# members read at run time: get(Bc::X) outside battle_config/ (and the mob_db members of battle_config/mod.rs)
readers = {}
for p, t in texts.items():
    if p.startswith('src/battle_config/'):
        continue
    for m in re.finditer(r'\bget\((?:crate::battle_config::)?Bc::(\w+)\)', t):
        readers.setdefault(m.group(1), set()).add(p[4:])
# ... and by name: battle_get_value("setting") (and its local aliases bc / bf), outside the unit tests
by_setting = {v[2].lower(): v[0] for v in members.values()}
for p, t in texts.items():
    if p.startswith('src/battle_config/'):
        continue
    body = t.split('#[cfg(test)]')[0]
    for m in re.finditer(r'\b(?:battle_get_value|bc|bf)\("([a-zA-Z_.0-9]+)"', body):
        ident = by_setting.get(m.group(1).lower())
        if ident:
            readers.setdefault(ident, set()).add(p[4:] + ' (by name)')
mod = texts['src/battle_config/mod.rs']
mobdb = re.search(r'pub const MOBDB_MEMBERS: \[Bc; MOBDB_N\] = \[(.*?)\];', mod, re.S).group(1)
for ident in re.findall(r'Bc::(\w+)', mobdb):
    readers.setdefault(ident, set()).add('mob/rtdb.rs (when mob_db loads)')

# members that still have a constant somewhere
CONST = re.compile(r'^\s*(?:pub(?:\([a-z:]+\))? )?const (\w+): ([\w:<>&\[\]\' ]+) = ([^;]+);', re.M)
consts = {}
for p, t in texts.items():
    if p.startswith('src/battle_config/') or p == 'src/script/battle_flags.rs':
        continue
    for m in CONST.finditer(t):
        low = m.group(1).lower()
        member = low if low in members else names.get(low)
        if member is not None and m.group(1) != 'MAX_WALK_SPEED':  # status.hpp's #define, not the setting
            consts.setdefault(members[member][0], []).append('%s %s = %s' % (p[4:], m.group(1), m.group(3).strip()[:40]))

# members datagen consumes when it builds the data (tools/datagen_mods), besides the mob_db members the module
# applies again; area_size only caps an item's attack range there
BAKED = '''mob_skill_rate mob_skill_delay mob_max_skilllvl mob_critical_rate critical_rate
enable_critical enable_perfect_flee
enable_baseatk_renewal item_group_rate item_group_drop_min item_group_drop_max max_parameter max_baby_parameter
max_trans_parameter max_third_parameter max_third_trans_parameter max_baby_third_parameter max_extended_parameter
max_summoner_parameter max_fourth_parameter max_trait_parameter use_statpoint_table use_traitpoint_table
start_status_points display_hallucination defunit_not_enemy hom_max_level hom_S_max_level require_glory_guild
feature_achievement'''.split()
baked = set()
for b in BAKED:
    if b not in members and b in names:
        b = names[b]
    if b not in members:
        print('not a battle_config member: ' + b)
        continue
    baked.add(members[b][0])

converted = sorted((i for i in readers if i not in consts and i not in baked), key=lambda i: by_ident[i][1])
partial_const = sorted((i for i in readers if i in consts), key=lambda i: by_ident[i][1])
partial_baked = sorted((i for i in readers if i in baked and i not in consts), key=lambda i: by_ident[i][1])
const_only = sorted((i for i in consts if i not in readers), key=lambda i: by_ident[i][1])
rest = sorted((i for i in by_ident if i not in readers and i not in consts), key=lambda i: by_ident[i][1])

out = []
out.append('//! GENERATED by the conversion (server/ARCHITECTURE.md, "The lists"): the battle_config members every reader of')
out.append('//! which goes through `battle_config::get` (or, for the members mob_db consumes, through the copy `mob_load` takes).')
out.append('//! A member that still has a build constant somewhere, or that datagen bakes into the embedded data, is not here:')
out.append('//! setting it is stored and shown by getbattleflag, as on rAthena, and logged as not (fully) followed by the rules')
out.append('//! (battle_config/mod.rs `not_read_yet`).')
out.append('')
out.append('use super::Bc;')
out.append('')
out.append('#[rustfmt::skip]')
out.append('pub const CONVERTED: &[Bc] = &[')
for i in converted:
    out.append('    Bc::%s, // %s' % (i, ', '.join(sorted(readers[i]))[:90]))
out.append('];')
out.append('')
out.append('pub fn is_converted(k: Bc) -> bool {')
out.append('    CONVERTED.contains(&k)')
out.append('}')
out.append('')
open('src/battle_config/converted.rs', 'w', encoding='utf-8', newline='\n').write('\n'.join(out))

sn = lambda i: by_ident[i][2]
print('CONVERTED %d' % len(converted))
print(' '.join(sn(i) for i in converted))
print('PARTIAL_CONST %d' % len(partial_const))
for i in partial_const:
    print('  %s: %s' % (sn(i), '; '.join(consts[i])))
print('PARTIAL_BAKED %d' % len(partial_baked))
print(' '.join(sn(i) for i in partial_baked))
print('CONST_ONLY %d' % len(const_only))
for i in const_only:
    print('  %s: %s' % (sn(i), '; '.join(consts[i])))
print('REST %d' % len(rest))
print(' '.join(sn(i) for i in rest))
